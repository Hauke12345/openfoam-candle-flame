"""Generate a 2D axisymmetric candle flame case for OpenFOAM v2412 (rhoReactingBuoyantFoam).

Physics:
  - laminar, compressible, buoyant (gravity -z), 2-step Westbrook-Dryer chemistry for n-dodecane
    (wax-vapour surrogate) with CO/CO2 equilibrium step
  - thermo (NASA7/janaf) from Cantera nDodecane_Reitz species data
  - Sutherland viscosity fitted to Cantera kinetic-theory viscosity
  - P1 radiation, grey-gas CO2/H2O absorption
  - wick = fuel-vapour source with a measured-candle mass burning rate
"""
import math, os, shutil, sys
import numpy as np
sys.path.insert(0, os.path.join(os.path.dirname(__file__), 'calib'))
import cantera as ct
from mech import with_transport

CASE = sys.argv[1] if len(sys.argv) > 1 else 'case'
BURN_G_PER_MIN = 0.10          # typical household paraffin candle
WEDGE_DEG = 5.0
T_WICK, T_POOL, T_AIR = 600.0, 340.0, 300.0

# ---------------- geometry (metres) ----------------
r1, r2, r3 = 0.75e-3, 10e-3, 40e-3      # wick radius, candle radius, domain radius
z1, z2 = 6e-3, 0.12                     # exposed wick length, domain height
NR = dict(a=6, b=45, c=25)              # axis-wick, wick-candle edge, candle edge-outer
NZ = dict(a=30, b=160)
GR = dict(b=8.0, c=6.0, zb=10.0)

FOAM_HDR = """/*--------------------------------*- C++ -*----------------------------------*\\
  candle flame case, generated by gen.py
\\*---------------------------------------------------------------------------*/
FoamFile
{{
    version     2.0;
    format      ascii;
    class       {cls};
    {loc}object      {obj};
}}
"""
def write(path, body, cls='dictionary', loc=''):
    full = os.path.join(CASE, path)
    os.makedirs(os.path.dirname(full), exist_ok=True)
    obj = os.path.basename(path)
    with open(full, 'w') as f:
        f.write(FOAM_HDR.format(cls=cls, obj=obj, loc=(f'location    "{loc}";\n    ' if loc else '')))
        f.write(body)

# ---------------- species thermo + transport ----------------
SP = {'C12H26': 'c12h26', 'O2': 'o2', 'N2': 'n2', 'CO': 'co', 'CO2': 'co2', 'H2O': 'h2o'}
allsp = {s.name: s for s in with_transport(ct.Species.list_from_file('nDodecane_Reitz.yaml'))}
gas = ct.Solution(thermo='ideal-gas', kinetics='gas', transport_model='mixture-averaged',
                  species=[allsp[v] for v in SP.values()], reactions=[])

def suth_fit(name):
    Ts_ = np.linspace(300, 2500, 45)
    mus = []
    for T in Ts_:
        gas.TPX = T, ct.one_atm, {name: 1.0}
        mus.append(gas.viscosity)
    mus = np.array(mus)
    # mu = As sqrt(T)/(1+Ts/T)  ->  sqrt(T)/mu = 1/As + (Ts/As)/T  (linear in 1/T)
    A = np.vstack([np.ones_like(Ts_), 1 / Ts_]).T
    c, *_ = np.linalg.lstsq(A, np.sqrt(Ts_) / mus, rcond=None)
    As = 1 / c[0]; Tsu = c[1] * As
    err = np.max(np.abs(As * np.sqrt(Ts_) / (1 + Tsu / Ts_) / mus - 1))
    return As, Tsu, err

def refit_1000(s):
    # refit NASA7 with switch at 1000 K (OpenFOAM janaf mixtures need a common Tcommon)
    th = s.thermo; Rg = ct.gas_constant
    cpR = lambda T: th.cp(T) / Rg
    def fit(T0, T1, pin=None):
        Ts_ = np.linspace(T0, T1, 200)
        A = np.vstack([Ts_**k for k in range(5)]).T
        b = np.array([cpR(T) for T in Ts_])
        if pin is None:
            return np.linalg.lstsq(A, b, rcond=None)[0]
        Tp, cpp = pin                      # constrain cp(Tp)=cpp: a0 = cpp - sum a_k Tp^k
        A2 = A[:, 1:] - np.array([Tp**k for k in range(1, 5)])
        a = np.linalg.lstsq(A2, b - cpp, rcond=None)[0]
        return np.concatenate([[cpp - sum(a[k-1]*Tp**k for k in range(1, 5))], a])
    lo5 = fit(max(th.min_temp, 200), 1000.0)
    cp1000 = sum(lo5[k]*1000.0**k for k in range(5))
    hi5 = fit(1000.0, th.max_temp, pin=(1000.0, cp1000))
    hint = lambda a, T: sum(a[k]*T**(k+1)/(k+1) for k in range(5))
    sint = lambda a, T: a[0]*math.log(T) + sum(a[k]*T**k/k for k in range(1, 5))
    T0 = 298.15
    a6l = th.h(T0)/Rg - hint(lo5, T0); a7l = th.s(T0)/Rg - sint(lo5, T0)
    a6h = hint(lo5, 1000) + a6l - hint(hi5, 1000); a7h = sint(lo5, 1000) + a7l - sint(hi5, 1000)
    lo = np.concatenate([lo5, [a6l, a7l]]); hi = np.concatenate([hi5, [a6h, a7h]])
    err = max(abs(sum((lo5 if T <= 1000 else hi5)[k]*T**k for k in range(5)) / cpR(T) - 1) for T in np.linspace(300, 3000, 60))
    print(f'{s.name}: refit to Tcommon 1000 K, max cp error {100*err:.2f}%')
    return 1000.0, hi, lo

thermo_txt, fit_report = '', []
for of, cn in SP.items():
    s = allsp[cn]
    c = s.thermo.coeffs
    Tmid, hi, lo = c[0], np.array(c[1:8]), np.array(c[8:15])
    if abs(Tmid - 1000.0) > 1e-6:
        Tmid, hi, lo = refit_1000(s)
    # enforce cp, h, s continuity at Tmid (some mechanism fits jump there, which breaks OpenFOAM's T inversion)
    cp = lambda a, T: a[0] + a[1]*T + a[2]*T**2 + a[3]*T**3 + a[4]*T**4
    hRT = lambda a, T: a[0] + a[1]*T/2 + a[2]*T**2/3 + a[3]*T**3/4 + a[4]*T**4/5 + a[5]/T
    sR = lambda a, T: a[0]*math.log(T) + a[1]*T + a[2]*T**2/2 + a[3]*T**3/3 + a[4]*T**4/4 + a[6]
    jump = cp(lo, Tmid) - cp(hi, Tmid)
    hi = hi.copy(); hi[0] += jump
    hi[5] += (hRT(lo, Tmid) - hRT(hi, Tmid)) * Tmid
    hi[6] += sR(lo, Tmid) - sR(hi, Tmid)
    fit_report.append(f'{of}: Tmid={Tmid:.0f} cp jump {jump:.3e} R fixed')
    As, Tsu, err = suth_fit(cn)
    fit_report.append(f'{of}: As={As:.4e} Ts={Tsu:.1f} max fit err {100*err:.1f}%')
    elems = '\n'.join(f'        {e} {int(n)};' for e, n in s.composition.items())
    f7 = lambda a: ' '.join(f'{x:.8e}' for x in a)
    thermo_txt += f"""
{of}
{{
    specie {{ molWeight {s.molecular_weight:.5f}; }}
    elements
    {{
{elems}
    }}
    thermodynamics
    {{
        Tlow {s.thermo.min_temp:.1f};
        Thigh {s.thermo.max_temp:.1f};
        Tcommon {Tmid:.1f};
        highCpCoeffs ( {f7(hi)} );
        lowCpCoeffs ( {f7(lo)} );
    }}
    transport {{ As {As:.6e}; Ts {Tsu:.4f}; }}
}}
"""
write('constant/thermo.compressibleGas', thermo_txt)
print('\n'.join(fit_report))

