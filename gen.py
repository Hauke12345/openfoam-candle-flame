# radiation: P1 + grey CO2/H2O (coefficients from OpenFOAM SandiaD tutorial, Smith/Shen/Friedman fits)
# grey-gas CO2/H2O absorption coefficients from the OpenFOAM SandiaD_LTS tutorial (GPL-3.0, copied to data/)
rp = open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'data', 'radiationProperties.SandiaD_LTS')).read()
import re
rp = re.sub(r'\n    CH4\n    \{.*?\n    \}\n', '\n', rp, flags=re.S)
os.makedirs(os.path.join(CASE, 'constant'), exist_ok=True)
open(os.path.join(CASE, 'constant/radiationProperties'), 'w').write(rp)
